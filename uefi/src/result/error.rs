//! Module for UEFI-specific error encodings. See [`Error`].

use super::Status;
use core::fmt::{Debug, Display};

/// UEFI error with optional additional data.
///
/// [`Status`] identifies the error kind and `Data` carries contextual payload.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Error<Data: Debug = ()> {
    status: Status,
    data: Data,
}

impl<Data: Debug> Error<Data> {
    /// Creates an [`Error`].
    ///
    /// # Panics
    ///
    /// Panics if `status` is [`Status::SUCCESS`].
    pub const fn new(status: Status, data: Data) -> Self {
        assert!(!matches!(status, Status::SUCCESS));
        Self { status, data }
    }

    /// Returns the error status.
    pub const fn status(&self) -> Status {
        self.status
    }

    /// Returns the error data.
    pub const fn data(&self) -> &Data {
        &self.data
    }

    /// Splits this error into its status and data.
    pub fn split(self) -> (Status, Data) {
        (self.status, self.data)
    }
}

// Errors without error data can be autogenerated from statuses

impl From<Status> for Error<()> {
    fn from(status: Status) -> Self {
        Self::new(status, ())
    }
}

impl<Data: Debug> Display for Error<Data> {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "UEFI Error {}: {:?}", self.status(), self.data())
    }
}

impl<Data: Debug> Error<Data> {
    /// Returns this error without its payload.
    ///
    /// This retains the status while simplifying the error type to [`Error<()>`].
    pub const fn to_err_without_payload(&self) -> Error<()> {
        Error {
            status: self.status,
            data: (),
        }
    }
}

impl<Data: Debug> core::error::Error for Error<Data> {}
